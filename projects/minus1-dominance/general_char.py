"""
GENERAL exact characterization (any modulus N where -1 is a nonsquare),
via the variance form V(N;a,1) = sum_{chi!=chi0} c_chi |chi(a)-1|^2.

delta(N;a,1) = 1/2 + rho(N)/sqrt(2 pi V(N;a,1)) + O(rho^3 V^{-3/2})   [FM Thm 1.1].
rho(N) = #real chars (SAME for all a). So to two-term order:
   delta(N;a,1) decreasing in V(N;a,1).
   '-1 tops delta among NR'  <=>  V(N;-1,1) = MIN_{a NR} V(N;a,1).

Decompose V by parity. Write c_chi = c_chi. For ANY a:
   |chi(a)-1|^2 = 2 - 2 Re chi(a).
   V(N;a,1) = sum_{chi!=chi0} c_chi (2 - 2 Re chi(a))
            = 2 C_tot - 2 sum_chi c_chi Re chi(a),   C_tot=sum_{chi!=chi0} c_chi.
So V(N;a,1) is MINIMIZED  <=>  S(a):=sum_{chi!=chi0} c_chi Re chi(a) is MAXIMIZED.
For a=-1: chi(-1)=+-1 real, Re chi(-1)=chi(-1). So
   S(-1) = sum_{even chi!=chi0} c_chi  -  sum_{odd chi} c_chi  = C_even - C_odd.
'-1 tops delta'  <=>  S(-1) = C_even - C_odd  is the MAX of S(a) over NR a.

We compute c_chi (analytic closed form) and test, including the N=8 group
(Z/2 x Z/2, no primitive root) which the prime formula does NOT cover.
"""
import mpmath as mp
mp.mp.dps = 25
import cmath, math

def char_table(N):
    """All Dirichlet chars mod N as dict a->complex, returns list of chars +parity."""
    units=[a for a in range(1,N) if math.gcd(a,N)==1]
    # group structure via SNF-free brute force: characters = homs to C*.
    # Use the standard construction through CRT-free direct enumeration:
    # find generators by building the group as product of cyclic factors.
    # Simple approach: enumerate all functions? Too big. Use known small N only.
    from sympy.ntheory.residue_ntheory import primitive_root
    pr=primitive_root(N)
    if pr is not None:
        g=pr; phi=len(units)
        idx={}; x=1
        for k in range(phi):
            idx[x]=k; x=(x*g)%N
        chars=[]
        for j in range(phi):
            ch={a: cmath.exp(2j*math.pi*j*idx[a]/phi) for a in units}
            chars.append(ch)
        return units, chars
    # no primitive root: handle N=8 explicitly (gens 3,5 ; orders 2,2; also need full)
    if N==8:
        # (Z/8)* = {1,3,5,7}, generated by 3 (ord2) and 5 (ord2); 7=3*5
        gens=[(3,2),(5,2)]
        # element -> exponent vector
        def expvec(a):
            for e1 in range(2):
                for e2 in range(2):
                    if (pow(3,e1,8)*pow(5,e2,8))%8==a%8:
                        return (e1,e2)
        chars=[]
        for j1 in range(2):
            for j2 in range(2):
                ch={a: cmath.exp(2j*math.pi*(j1*expvec(a)[0]/2 + j2*expvec(a)[1]/2)) for a in units}
                chars.append(ch)
        return units, chars
    raise NotImplementedError(N)

def cchi_analytic(N, ch, units):
    """c_chi = log(N/pi) + psi((1+a_chi)/2) + 2 Re L'/L(1,chi*).
    a_chi = parity (0 even,1 odd). Use conductor=N for primitive (small N prime);
    for our small N all nonprincipal chars are primitive except imprimitive ones
    mod 8 (the chi induced by mod4). We approximate L'/L(1,chi) by truncated prime
    sum over the char itself (good enough for ORDERING; matches canonical_verify)."""
    a_chi = 0 if abs(ch[N-1]-1)<1e-9 else 1   # chi(-1)=+1 even else odd
    # Re L'/L(1,chi) = Re( -sum_{p,k} log p * chi(p^k)/p^k )
    s=mp.mpf(0)
    from sympy import primerange
    for p in primerange(2, 200000):
        if math.gcd(p,N)!=0 and (p%N) in units:
            pk=p; k=1
            while pk< 200000:
                cval=ch[pk%N]
                s+= mp.log(p)*cval.real/pk   # Re chi(p^k)/p^k (chi real-ish part)
                # NOTE: chi complex; take real part of chi(p^k)/p^k * (we want Re of full)
                pk*=p; k+=1
    ReLL = -s
    val = mp.log(N/mp.pi) + mp.digamma((1+a_chi)/mp.mpf(2)) + 2*ReLL
    return val, a_chi

def analyze(N):
    units,chars=char_table(N)
    phi=len(units)
    # identify principal (all ones)
    cdat=[]
    for ch in chars:
        if all(abs(ch[a]-1)<1e-9 for a in units):
            continue  # principal
        c,a_chi=cchi_analytic(N,ch,units)
        cdat.append((ch,float(c),a_chi))
    C_even=sum(c for ch,c,p in cdat if p==0)
    C_odd =sum(c for ch,c,p in cdat if p==1)
    # nonsquares
    sqs=set((x*x)%N for x in units)
    NRs=[a for a in units if a not in sqs]
    def S(a):
        return sum(c*(ch[a].real) for ch,c,p in cdat)
    def V(a):
        return sum(c*abs(ch[a]-1)**2 for ch,c,p in cdat)
    rows=[]
    for a in NRs:
        rows.append((a, V(a), S(a)))
    rows.sort(key=lambda r:r[1])  # ascending V = descending delta
    m1=N-1
    Vm1=V(m1)
    Vmin=min(r[1] for r in rows)
    tops = abs(Vm1-Vmin)<1e-6
    print(f"--- N={N}  phi={phi}  C_even={C_even:.5f}  C_odd={C_odd:.5f}  "
          f"S(-1)=C_even-C_odd={C_even-C_odd:.5f} ---")
    print(f"   NR ranked by V ascending (=delta descending; rank1 => TOP delta):")
    for i,(a,Va,Sa) in enumerate(rows):
        tag=" <== a=-1" if a==m1 else ""
        print(f"     a={a:3d}  V={Va:9.4f}  S(a)={Sa:8.4f}  delta-rank={i+1}{tag}")
    print(f"   -1 is delta-TOP (V-min)? {tops}.  "
          f"-1 V-rank-by-size(1=largest)={1+sum(1 for r in rows if r[1]>Vm1+1e-9)}")
    print()
    return tops

