# main
# --------------------------------------------------------------------------
def main():
    dps = 30
    results = {
        "method": ("Hejhal automorphy point-matching, ODD (sine) Maass forms; "
                   "indicator = smallest singular value of the column-normalized "
                   "implicit-automorphy matrix W(r)=B-C(r), in mpmath dps=30. "
                   "sqrt(y) Whittaker prefactor included."),
        "independence_note": ("Does NOT use/import the Mayer transfer-operator code. "
                              "Reuses the validated hejhal_g5_maass machinery, "
                              "parametrized by lambda."),
        "surfaces": {},
    }

    # ----------------------------------------------------------------------
    # (A) Modular anchor re-validation (lambda=1).  Known odd r1=9.533695.
    #     Confirms the parametrized code still reproduces the anchor.
    # ----------------------------------------------------------------------
    print("\n=== MODULAR ANCHOR re-validation  (lambda=1, known odd r1=9.533695) ===",
          flush=True)
    surf = MODULAR
    Y0 = 0.65
    target = 9.533695
    M = auto_M(surf, target, Y0)
    Q = 2 * M + 8
    rstar, vstar, grid = locate_dip(surf, target, M, Y0, Q, dps, half_window=0.25, n_grid=21)
    print(f"   --> modular r* = {rstar:.5f}   sigma_min = {vstar:.3e}   "
          f"(known 9.533695, diff={rstar-9.533695:+.5f})", flush=True)
    results["surfaces"]["modular"] = {
        "lambda": surf.lam, "kappa": surf.kappa, "Y0": Y0, "M": M, "Q": Q, "dps": dps,
        "known_r": 9.533695, "r_star": rstar, "sigma_min": vstar,
        "diff": rstar - 9.533695, "scan_grid": grid,
    }

    # ----------------------------------------------------------------------
    # (B) G_8 targets  (lambda_8 = 2cos pi/8 ~ 1.84776, corner y ~ 0.3827).
    #     TO claim: r1=5.798144, r2=7.767443.  Use Y0 ~ 0.30 (below corner).
    #     Height-independence check: re-locate r1 at a second Y0.
    # ----------------------------------------------------------------------
    g8 = make_Gq(8)
    print(f"\n=== G_8  lambda={g8.lam:.10f}  kappa={g8.kappa:.6f}  "
          f"FD corner y={g8.y_corner:.6f} ===", flush=True)
    g8_targets = [5.798144, 7.767443]
    Y0_g8 = 0.30
    g8_located = []
    for target in g8_targets:
        M = auto_M(g8, target, Y0_g8)
        Q = 2 * M + 8
        print(f"\n--- G_8 scan around TO r~{target}  (M={M},Q={Q},Y0={Y0_g8}) ---",
              flush=True)
        rstar, vstar, grid = locate_dip(g8, target, M, Y0_g8, Q, dps,
                                        half_window=0.30, n_grid=25)
        print(f"   --> G_8 r* = {rstar:.5f}   sigma_min = {vstar:.3e}   "
              f"(TO={target}, diff={rstar-target:+.5f})", flush=True)
        g8_located.append({
            "TO_claim": target, "M": M, "Q": Q, "Y0": Y0_g8, "dps": dps,
            "r_star": rstar, "sigma_min": vstar, "diff_from_TO": rstar - target,
            "scan_grid": grid,
        })

    # Height-independence: re-locate r1 at a different Y0 (rules out artifacts).
    Y0_g8_b = 0.24
    t1 = g8_targets[0]
    Mb = auto_M(g8, t1, Y0_g8_b)
    Qb = 2 * Mb + 8
    print(f"\n--- G_8 HEIGHT-INDEPENDENCE check: r1 at Y0={Y0_g8_b} (M={Mb},Q={Qb}) ---",
          flush=True)
    rstar_b, vstar_b, grid_b = locate_dip(g8, t1, Mb, Y0_g8_b, Qb, dps,
                                          half_window=0.20, n_grid=17)
    print(f"   --> G_8 r1 at Y0={Y0_g8_b}: r*={rstar_b:.5f}  sigma_min={vstar_b:.3e}",
          flush=True)
    height_check = {
        "r1_Y0_a": {"Y0": Y0_g8, "r_star": g8_located[0]["r_star"],
                    "sigma_min": g8_located[0]["sigma_min"]},
        "r1_Y0_b": {"Y0": Y0_g8_b, "M": Mb, "Q": Qb, "r_star": rstar_b,
                    "sigma_min": vstar_b, "scan_grid": grid_b},
        "r_star_shift": rstar_b - g8_located[0]["r_star"],
    }

    results["surfaces"]["G_8"] = {
        "lambda": g8.lam, "kappa": g8.kappa, "y_corner": g8.y_corner,
        "TO_claims": g8_targets, "located": g8_located,
        "height_independence": height_check,
    }

    # ----------------------------------------------------------------------
    # (C) G_5 r_3 (secondary).  lambda = phi.  TO claim r_3 = 10.136450.
    # ----------------------------------------------------------------------
    g5 = make_Gq(5)
    print(f"\n=== G_5 r_3  lambda={g5.lam:.10f}  kappa={g5.kappa:.6f} ===", flush=True)
    Y0_g5 = 0.50
    t3 = 10.136450
    M = auto_M(g5, t3, Y0_g5)
    Q = 2 * M + 8
    print(f"--- G_5 scan around TO r_3~{t3}  (M={M},Q={Q},Y0={Y0_g5}) ---", flush=True)
    rstar, vstar, grid = locate_dip(g5, t3, M, Y0_g5, Q, dps, half_window=0.30, n_grid=25)
    print(f"   --> G_5 r_3* = {rstar:.5f}   sigma_min = {vstar:.3e}   "
          f"(TO={t3}, diff={rstar-t3:+.5f})", flush=True)
    results["surfaces"]["G_5_r3"] = {
        "lambda": g5.lam, "kappa": g5.kappa, "Y0": Y0_g5, "M": M, "Q": Q, "dps": dps,
        "TO_claim": t3, "r_star": rstar, "sigma_min": vstar,
        "diff_from_TO": rstar - t3, "scan_grid": grid,
    }

    os.makedirs(os.path.dirname(OUT_PATH), exist_ok=True)
    with open(OUT_PATH, "w") as f:
        json.dump(results, f, indent=2)
    print(f"\nWrote {OUT_PATH}")

    print("\n================ SUMMARY ================")
    m = results["surfaces"]["modular"]
    print(f"  MODULAR  known r=9.533695  Hejhal r*={m['r_star']:.5f}  "
          f"diff={m['diff']:+.5f}  sigma_min={m['sigma_min']:.2e}")
    for loc in results["surfaces"]["G_8"]["located"]:
        print(f"  G_8  TO r={loc['TO_claim']:8.5f}  Hejhal r*={loc['r_star']:.5f}  "
              f"diff={loc['diff_from_TO']:+.5f}  sigma_min={loc['sigma_min']:.2e}")
    hc = results["surfaces"]["G_8"]["height_independence"]
    print(f"  G_8  height-indep r1: Y0={hc['r1_Y0_a']['Y0']} -> {hc['r1_Y0_a']['r_star']:.5f} | "
          f"Y0={hc['r1_Y0_b']['Y0']} -> {hc['r1_Y0_b']['r_star']:.5f}  "
          f"shift={hc['r_star_shift']:+.2e}")
    g = results["surfaces"]["G_5_r3"]
    print(f"  G_5  TO r3={g['TO_claim']:8.5f}  Hejhal r*={g['r_star']:.5f}  "
          f"diff={g['diff_from_TO']:+.5f}  sigma_min={g['sigma_min']:.2e}")


if __name__ == "__main__":
    main()
