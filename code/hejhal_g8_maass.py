import numpy as np
import mpmath as mp

OUT_PATH = os.path.join(os.path.dirname(__file__), "out", "hejhal_g8_maass.json")


# --------------------------------------------------------------------------
# Surface container -- everything surface-dependent lives here so the SAME
# numerical core runs on lambda = 1 (modular), phi (G_5), 2cos(pi/8) (G_8).
# --------------------------------------------------------------------------
class Surface:
    def __init__(self, lam, name):
        self.lam = float(lam)
        self.name = name
        self.half = self.lam / 2.0
        self.kappa = 2.0 * math.pi / self.lam
        s2 = 1.0 - self.half * self.half
        self.y_corner = math.sqrt(s2) if s2 > 0 else float("nan")


def make_Gq(q):
    return Surface(2.0 * math.cos(math.pi / q), f"G_{q} = (2,{q},inf)")


MODULAR = Surface(1.0, "SL(2,Z) modular")


# --------------------------------------------------------------------------
# 1.  Pullback into the fundamental domain (nearest-lambda reduction + S).
#     Identical algorithm to hejhal_g5_maass.pullback, parametrized by surf.
# --------------------------------------------------------------------------
def pullback(surf, x, y, max_iter=10000):
    lam, half = surf.lam, surf.half
    z = complex(x, y)
    for _ in range(max_iter):
        n = math.floor(z.real / lam + 0.5)
        if n != 0:
            z = complex(z.real - n * lam, z.imag)
        r2 = z.real * z.real + z.imag * z.imag
        if r2 < 1.0 - 1e-15:
            z = -1.0 / z
        else:
            if abs(z.real) <= half + 1e-12:
                return z.real, z.imag
    return z.real, z.imag


# --------------------------------------------------------------------------
# 2.  mpmath column-normalized Hejhal matrix  W(r) = B - C(r)  for ODD forms.
#     Verbatim port of hejhal_g5_maass.build_W_mp with surf-parametrized
#     lambda / kappa / half.  sqrt(y) Whittaker prefactor included.
# --------------------------------------------------------------------------
def build_W_mp(surf, r, M, Y0, Q, dps=30):
    with mp.workdps(dps):
        rr = mp.mpf(r)
        Y0m = mp.mpf(Y0)
        kappa = mp.mpf(surf.kappa)
        half = mp.mpf(surf.half)
        order = mp.mpc(0, rr)

        xs = [half * (mp.mpf(j) - mp.mpf('0.5')) / Q for j in range(1, Q + 1)]
        xs_f = [float(x) for x in xs]
        pb = [pullback(surf, x, Y0) for x in xs_f]
        xstar = [mp.mpf(p[0]) for p in pb]
        ystar = [mp.mpf(p[1]) for p in pb]

        KY0 = [mp.besselk(order, kappa * (n + 1) * Y0m).real for n in range(M)]

        SIN_samp = [[mp.sin(kappa * (n + 1) * xs[j]) for j in range(Q)] for n in range(M)]
        SIN_star = [[mp.sin(kappa * (n + 1) * xstar[j]) for j in range(Q)] for n in range(M)]
        # sqrt(y) Whittaker prefactor: RHS picks up sqrt(y*_j / Y0). Essential.
        sqrt_fac = [mp.sqrt(ystar[j] / Y0m) for j in range(Q)]
        KR = [[mp.besselk(order, kappa * (n + 1) * ystar[j]).real / KY0[n] for j in range(Q)]
              for n in range(M)]
        PHI = [[sqrt_fac[j] * KR[n][j] * SIN_star[n][j] for j in range(Q)] for n in range(M)]

        twoQ = 2 / mp.mpf(Q)
        W = mp.matrix(M, M)
        for l in range(M):
            srow = SIN_samp[l]
            for n in range(M):
                B = mp.mpf(0)
                C = mp.mpf(0)
                sn = SIN_samp[n]
                pn = PHI[n]
                for j in range(Q):
                    slj = srow[j]
                    B += slj * sn[j]
                    C += slj * pn[j]
                W[l, n] = twoQ * (B - C)
        return W


def _is_real(G):
    for i in range(G.rows):
        for j in range(G.cols):
            if abs(mp.im(G[i, j])) > mp.mpf(10) ** (-mp.mp.dps + 5):
                return False
    return True


def _mp_smallest_sv(W):
    n = W.rows
    G = W.H * W
    for i in range(n):
        for j in range(n):
            G[i, j] = (G[i, j] + mp.conj(G[j, i])) / 2
    ev = mp.eigsy(G, eigvals_only=True) if _is_real(G) else mp.eig(G, left=False, right=False)
    vals = [abs(mp.re(e)) for e in ev]
    vals = [v for v in vals if v >= 0]
    smin = mp.sqrt(min(vals))
    smax = mp.sqrt(max(vals))
    return smin, smax


def sigma_min_mp(surf, r, M, Y0, Q, dps=30):
    with mp.workdps(dps):
        W = build_W_mp(surf, r, M, Y0, Q, dps)
        smin, smax = _mp_smallest_sv(W)
        return float(smin), float(smax)


def smin_only(surf, r, M, Y0, Q, dps=30):
    return sigma_min_mp(surf, r, M, Y0, Q, dps)[0]


# --------------------------------------------------------------------------
# 3.  Scan + golden-section refine of the sigma_min dip.
# --------------------------------------------------------------------------
def golden_refine(f, a, b, tol=1e-4, max_iter=40):
    gr = (math.sqrt(5) - 1) / 2
    c = b - gr * (b - a)
    d = a + gr * (b - a)
    fc, fd = f(c), f(d)
    for _ in range(max_iter):
        if abs(b - a) < tol:
            break
        if fc < fd:
            b, d, fd = d, c, fc
            c = b - gr * (b - a)
            fc = f(c)
        else:
            a, c, fc = c, d, fd
            d = a + gr * (b - a)
            fd = f(d)
    rmin = (a + b) / 2
    return rmin, f(rmin)


def locate_dip(surf, target, M, Y0, Q, dps, half_window=0.30, n_grid=25, verbose=True):
    lo, hi = target - half_window, target + half_window
    rr = np.linspace(lo, hi, n_grid)
    vals = []
    for r in rr:
        s = smin_only(surf, float(r), M, Y0, Q, dps)
        vals.append(s)
        if verbose:
            print(f"    r={r:.4f}  sigma_min={s:.4e}", flush=True)
    vals = np.array(vals)
    k = int(np.argmin(vals))
    a = rr[max(0, k - 1)]
    b = rr[min(len(rr) - 1, k + 1)]
    rstar, vstar = golden_refine(lambda r: smin_only(surf, r, M, Y0, Q, dps), a, b,
                                 tol=1e-4, max_iter=40)
    return float(rstar), float(vstar), [[float(r), float(v)] for r, v in zip(rr, vals)]


def auto_M(surf, target, Y0):
    """Truncation: need kappa*M*Y0 comfortably > r so the Fourier tail decays."""
    return int(target / (surf.kappa * Y0)) + 14


