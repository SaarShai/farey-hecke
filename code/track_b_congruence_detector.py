def analyze(sig,tau,name):
    labels=track_labels(orbit, sig, tau)
    n=len(sig)
    print(f"\n[{name}] coset-label distribution:", Counter(labels))
    # support edge of FULL section (no coset restriction) = global BCZ edge
    # For each coset sheet compute support edge and cluster ceiling at that edge*(1+eps)
    results=[]
    for c in range(n):
        edge=support_edge(orbit,labels,c)
        if edge is None: continue
        # cluster ceiling = longest run with P below a small quantile threshold X.
        # Use the GLOBAL section onset analogue: X = edge*1.0001 won't give runs;
        # use the extreme-gap onset = the 0.5% quantile of the sub-orbit P's as the
        # "rare small-gap" threshold, mirroring the Hecke cluster definition (P<X).
        subP=np.array([orbit[i][2] for i in range(len(orbit)) if labels[i]==c])
        X=np.quantile(subP,0.01)
        B,m=cluster_ceiling_for_coset(orbit,labels,c,X)
        results.append((c,edge,X,B,m))
    for (c,edge,X,B,m) in results:
        print(f"   coset {c}: support_edge={edge:.6f}  X(1%q)={X:.6f}  ceiling B={B}  (#returns={m})")
    Bmax=max(r[3] for r in results)
    edges=[r[1] for r in results]
    print(f"   --> MAX cluster ceiling over cosets = {Bmax};  min support edge = {min(edges):.6f}")
    return Bmax, min(edges)

