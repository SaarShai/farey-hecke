# Congruence test via Wohlfahrt+monodromy: a transitive PSL2Z action of index n
# and level N is CONGRUENCE iff its monodromy is a quotient of PSL2(Z/N).
# |PSL2(Z/N)|: N=2:6, 3:12, 4:48, 5:60, 6:72(=PSL2(2)xPSL2(3)? CRT 6*... ), 7:168.
def psl2_modN_order(N):
    # |SL2(Z/N)| = N^3 prod_{p|N}(1-1/p^2); PSL2 = that /2 for N>2, /1 for N=2
    from sympy import primefactors
    sl=N**3
    for p in primefactors(N):
        sl = sl*(p*p-1)//(p*p)
    return sl if N<=2 else sl//2

for N in [2,3,4,5,6,7,12]:
    print(f"|PSL2(Z/{N})| = {psl2_modN_order(N)}")

