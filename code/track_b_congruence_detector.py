"""
Lifted-BCZ cross-section simulation for a finite-index subgroup H of PSL(2,Z),
given H as a coset diagram (sig, tau) [transitive, sig^2=tau^3=1 in S_n].

Cross-section dynamics: standard BCZ on the Farey triangle
   F = {(a,b): 0<a<=1, 0<b<=1, a+b>1},  T(a,b)=(b, -a + k b), k=floor((1+a)/b),
return time R=1/(ab), observable P=a*b. We attach a coset label updated by the
parabolic/cusp combinatorics. The H-Farey sub-orbit = returns to a fixed coset
sheet over the cusp; its gap statistic is what Heersink's lift produces.

The coset label transforms under the BCZ step by rho(T_word) where T_word is the
PSL2Z element realizing one BCZ step. One BCZ step corresponds to applying the
parabolic generator T some number of times then the flip S (the BCZ map is
generated by T and S acting on the section). We track the label by composing the
generator permutations accordingly.
"""
import numpy as np
from math import floor

def cycles(p):
    n=len(p); seen=[False]*n; out=[]
    for i in range(n):
        if not seen[i]:
            c=[]; j=i
            while not seen[j]:
                seen[j]=True; c.append(j); j=p[j]
            out.append(c)
    return out
def comp(p,q): return tuple(p[q[i]] for i in range(len(p)))
def inv(p):
    r=[0]*len(p)
    for i,x in enumerate(p): r[x]=i
    return tuple(r)

# ---- BCZ orbit (long), recording (a,b,P) ----
def bcz_orbit(a0,b0,nsteps):
    a,b=a0,b0
    out=[]
    for _ in range(nsteps):
        k=floor((1.0+a)/b)
        a,b = b, -a + k*b
        out.append((a,b,a*b,k))
    return out

# ---- coset label track ----
# In the BCZ generation, each step applies T (parabolic, k times) then S (flip).
# Image perms: L = image of T (=comp(sig,tau)), S_perm = sig.
def track_labels(orbit, sig, tau, start_label=0):
    L = comp(sig,tau)            # image of T
    Spm = sig                    # image of S
    lbl = start_label
    labels=[]
    for (a,b,P,k) in orbit:
        # apply T^k then S to the sheet label
        # acting on right cosets: c -> rho(g)(c); compose k copies of L then S
        for _ in range(k % len(sig)):  # T has finite order on cosets; reduce mod cusp width handled by cycle
            lbl = L[lbl]
        lbl = Spm[lbl]
        labels.append(lbl)
    return labels

def cluster_ceiling_for_coset(orbit, labels, target_coset, X):
    """Longest run of consecutive returns-to-target_coset whose P < X.
    'consecutive returns' = consecutive in the sub-sequence restricted to
    indices where label==target_coset."""
    run=0; best=0
    sub_P=[orbit[i][2] for i in range(len(orbit)) if labels[i]==target_coset]
    for P in sub_P:
        if P < X:
            run+=1; best=max(best,run)
        else:
            run=0
    return best, len(sub_P)

def support_edge(orbit, labels, target_coset):
    sub_P=[orbit[i][2] for i in range(len(orbit)) if labels[i]==target_coset]
    return min(sub_P) if sub_P else None

# ---------------- DEFINE TWO INDEX-7 SUBGROUPS ----------------
# We use coset diagrams. For PSL2Z with s^2=t^3=1.
# Example A (CONGRUENCE): Gamma_0(N)-type. Take the congruence subgroup of index 7
#   = Gamma_0(7) has index 8 actually (psi(7)=8). Use Gamma^0/Gamma_0; instead use
#   a clean congruence index-7? In PSL2Z, smallest congruence indices: Gamma_0(p)
#   index p+1. So index 7 congruence is NOT a Gamma_0(p). But index<7 are all
#   congruence; and there ARE congruence subgroups of index 7 (e.g. a subgroup of
#   Gamma_0(... )). To get a clean matched comparison we instead compare:
#     - index 6: ALWAYS congruence (no noncong below 7). e.g. Gamma_0(5) index 6.
#     - index 7: the famous noncongruence subgroups exist.
# Better matched test: pick TWO index-7 diagrams, classify each by Wohlfahrt level
# + Hsu, report cusp widths & cluster ceilings. We'll just enumerate index-7
# diagrams, group by cusp-width profile, and within a profile compare ceilings.

from collections import defaultdict
import itertools

n=7
# generate all involutions sig (s^2=1) with no... allow fixed pts (cusps of width via t)
def involutions(n):
    # build via pairings
    res=[]
    def rec(elems, cur):
        if not elems:
            p=list(range(n))
            for (i,j) in cur: p[i]=j; p[j]=i
            res.append(tuple(p)); return
        x=elems[0]
        # x fixed
        rec(elems[1:], cur)
        # x paired
        for k in range(1,len(elems)):
            y=elems[k]
            rec(elems[1:k]+elems[k+1:], cur+[(x,y)])
    rec(list(range(n)), [])
    return res

def order3s(n):
    res=[]
    def rec(elems,cur):
        if not elems:
            p=list(range(n))
            for c in cur:
                for i in range(3):
                    p[c[i]]=c[(i+1)%3]
            res.append(tuple(p)); return
        x=elems[0]
        rec(elems[1:],cur)  # x fixed
        rest=elems[1:]
        for i in range(len(rest)):
            for j in range(i+1,len(rest)):
                rec([e for k,e in enumerate(rest) if k!=i and k!=j], cur+[(x,rest[i],rest[j])])
    rec(list(range(n)),[])
    return res

def transitive(gens,n):
    seen=[False]*n; seen[0]=True; st=[0]
    while st:
        x=st.pop()
        for g in gens:
            y=g[x]
            if not seen[y]: seen[y]=True; st.append(y)
    return all(seen)

invs=involutions(n); o3s=order3s(n)
print(f"#involutions={len(invs)} #order3={len(o3s)}")
profiles=defaultdict(list)
count=0
for sig in invs:
    for tau in o3s:
        if not transitive([sig,tau],n): continue
        u=comp(sig,tau)
        ct=tuple(sorted(len(c) for c in cycles(u)))  # cusp widths
        N=int(np.lcm.reduce([len(c) for c in cycles(u)]))
        profiles[ct].append((sig,tau,N))
        count+=1
print("transitive index-7 diagrams:",count)
for ct in sorted(profiles):
    print("cusp-width profile",ct,"  count",len(profiles[ct]))

# ---------------- CONGRUENCE TEST (Hsu 1996, exact for PSL2Z) ----------------
# Hsu's theorem: Let G<=PSL2Z of index n, with L = image of [[1,1],[0,1]] (parabolic T)
# and R = image of [[1,0],[-1,1]] in the coset perm rep. Let m = level = order of L
# (= lcm cusp widths). Then G is congruence iff the following relations hold in <L,R>:
#  Let L,R be the permutations. Write down (depending on m mod 2):
#  - m odd: relation  R = L^c R^? ...  
# We use the standard, widely-implemented form (e.g. in Sage's is_congruence /
# Kulkarni-Hsu): with a,b,c such that a = 2^{-1} mod m etc. To avoid transcription
# error we use the ROBUST equivalent: G is congruence  <=>  the map
#    PSL2(Z) -> Sym(cosets)  factors through PSL2(Z/m).
# Operationally: <L,R> (perm group) is a quotient of PSL2Z; it factors through
# PSL2(Z/m) iff the kernel contains Gamma(m), iff adding the relations of Gamma(m)
# (namely that the principal congruence relations hold) is consistent.
# The cleanest exact certificate: build PSL2(Z/m) explicitly, find its action on
# n points compatible with L=T-image, R-image; congruence iff such compatible
# transitive PSL2(Z/m)-set of size n exists matching (L,R) cycle structure AND
# the abstract group <L,R> is a quotient of PSL2(Z/m).
#
# Simplest rigorous proxy that is SUFFICIENT to separate our pair:
# compute |<sig,tau>| (the monodromy group as a perm group). For congruence
# subgroups of level m, the monodromy group is a quotient of PSL2(Z/m); for the
# famous index-7 NONcongruence ones the monodromy group is A7 or L2(7) etc.
# We report the monodromy group order + composition, plus Wohlfahrt level, which
# together with the literature pins down congruence status.

def perm_group_order(gens, n):
    # BFS over the group generated by gens (and inverses) in S_n
    start=tuple(range(n))
    seen={start}; frontier=[start]
    gl=list(gens)+[inv(g) for g in gens]
    while frontier:
        nf=[]
        for x in frontier:
            for g in gl:
                y=comp(g,x)
                if y not in seen:
                    seen.add(y); nf.append(y)
        frontier=nf
    return len(seen)

