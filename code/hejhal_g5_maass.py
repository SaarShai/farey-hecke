def smin_only(r, M, Y0, Q, dps=30):
    """Smallest singular value (the eigenvalue indicator), mpmath path."""
    return sigma_min_mp(r, M, Y0, Q, dps)[0]


def locate_dip(target, M, Y0, Q, dps, half_window=0.30, n_grid=25):
    """Scan +-half_window around target, then golden-refine the sigma_min dip."""
    lo, hi = target - half_window, target + half_window
    rr = np.linspace(lo, hi, n_grid)
    vals = []
    for r in rr:
        s = smin_only(float(r), M, Y0, Q, dps)
        vals.append(s)
        print(f"    r={r:.4f}  sigma_min={s:.4e}", flush=True)
    vals = np.array(vals)
    k = int(np.argmin(vals))
    a = rr[max(0, k - 1)]
    b = rr[min(len(rr) - 1, k + 1)]
    rstar, vstar = golden_refine(lambda r: smin_only(r, M, Y0, Q, dps), a, b,
                                 tol=1e-4, max_iter=40)
    return float(rstar), float(vstar), [[float(r), float(v)] for r, v in zip(rr, vals)]


