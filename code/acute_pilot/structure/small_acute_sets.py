#!/usr/bin/env python3
"""Exact optimal acute (cubic) sets a(n) for small n, from OEIS A089676 / Bevan 2006.
Stored as 0/1 rows (string per point); rows_to_mask gives LSB=first column (matches verify.py)."""
SETS = {
1: ["0","1"],
2: ["00","11"],
3: ["000","011","101","110"],
4: ["0000","0011","0101","1001","1110"],
5: ["00000","00011","00101","01001","10001","11110"],
6: ["000000","000111","011001","011110","101010","101101","110011","110100"],
7: ["0000000","0000011","0001101","0110001","0111110","1010101","1011010","1100110","1101001"],
8: ["00000000","00000011","00000101","00011001","01100001","01111110","10101001","10110110","11001110","11010001"],
}
def to_mask(row):
    v=0
    for i,c in enumerate(row):
        if c=='1': v|=(1<<i)
    return v
def get(n):
    return [to_mask(r) for r in SETS[n]]
